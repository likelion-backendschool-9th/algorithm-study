class Solution {
    public int[] solution(int[][] edges) {
        // 제한사항 : 1 ≤ edges의 길이 ≤ 1,000,000
        // 정점 번호가 최대 1,000,000이므로 번호를 배열 인덱스로 사용한다.
        // 각 정점에 들어오는 간선 수를 저장
        int[] in = new int[1_000_001];
        // // 각 정점에 나가는 간선 수를 저장
        int[] out = new int[1_000_001];

        // [생성 정점 번호, 도넛 수, 막대 수, 8자 수]
        // 배열의 모든 값은 처음에 0
        int[] answer = new int[4];

        // 모든 간선을 확인하면서 각 정점의 간선 수를 카운트
        for (int[] edge : edges) {
            // edge = [a, b]는 a에서 b로 향하는 간선(a → b)
            out[edge[0]]++; // 출발 정점 a의 나가는 간선 수 +1
            in[edge[1]]++;  // 도착 정점 b의 들어오는 간선 수 +1
        }

        // 각 정점의 간선 수를 보고 생성 정점, 막대, 8자를 찾는다.
        for (int node = 1; node < in.length; node++) {
            if (in[node] == 0 && out[node] >= 2) {
                // 생성 정점: 들어오는 간선이 없고, 각 그래프로 간선을 보낸다.
                // 그래프가 총 2개 이상이므로 나가는 간선도 2개 이상이다.
                answer[0] = node;
            } else if (in[node] > 0 && out[node] == 0) {
                // 막대의 끝점: 들어오는 간선은 있지만 나가는 간선은 없다.
                // 막대마다 끝점이 하나이므로 끝점 수가 곧 막대 수
                // in > 0 조건은 실제로 없는 정점 번호를 세지 않기 위해 필요하다.
                answer[2]++;
            } else if (in[node] >= 2 && out[node] == 2) {
                // 8자의 중심점: 두 고리에서 간선이 들어오고, 두 고리로 나간다.
                // 생성 정점이 중심점에 연결되면 들어오는 간선은 3개가 된다.
                // 따라서 들어오는 간선은 2개 이상, 나가는 간선은 정확히 2개다.
                // 8자마다 중심점이 하나이므로 중심점 수가 곧 8자 수
                answer[3]++;
            }
        }

        // 전체 그래프 수에서 막대 수와 8자 수를 빼면 도넛 수다.
        // 생성 정점은 각 그래프에 간선을 하나씩 보내므로,
        // out[answer[0]]가 전체 그래프 수이다.
        answer[1] = out[answer[0]] - answer[2] - answer[3];

        // 문제에서 요구한 순서대로 반환
        return answer;
    }
}
